// Keep the vendored moSHion engine and its docs current with upstream (shuff57/moshion, `main`).
//
//   npm run sync:moshion              copy the engine, typings and docs from upstream main,
//                                     reapply shCode's one local line, regenerate the editor
//                                     autocomplete, run the moshion gates, stamp VENDORED.md
//   npm run sync:moshion -- --check   exit 1 if the vendored copy differs from upstream main,
//                                     or if it cannot be checked (no checkout, offline)
//                                     (deploy runs this; MOSHION_ALLOW_BEHIND=1 lets a deploy
//                                     go out anyway, for an urgent shCode-only fix)
//
// Not a runtime "@latest": students never load an untested engine. This is the
// one command that brings a tested copy in. Upstream checkout: ../moshion, or
// MOSHION_DIR. It reads a committed ref from git (origin/main, or MOSHION_REF,
// e.g. a local branch while a change is under review), never the working tree,
// so another session's uncommitted work there cannot leak in.
//
// What it copies: moshion.js (with the /moshion/textures/ base line),
// docs/moshion.d.ts, planck.min.js, and the built docs (docs/data/moshion-docs.js,
// written as lib/moshion-docs-shared.generated.ts). Textures, fonts, sounds,
// runner.html and extras.js are shCode's own or synced by their generators
// (see VENDORED.md). The docs are written ONCE, in the moshion repo's
// docs/content/; shCode's own pages are lib/moshion-docs-shcode.ts.

import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const upstream = resolve(process.env.MOSHION_DIR || join(root, '..', 'moshion'));
const REF = process.env.MOSHION_REF || 'origin/main';
const checkOnly = process.argv.includes('--check');
const vendored = join(root, 'public/moshion');
const NODE = ['--import', './scripts/register-ts.mjs'];

// The single line shCode changes in moshion.js: the empty-catalog fallback.
const UP_LINE = "return { base: 'textures/', textures: {} };";
const OUR_LINE = "return { base: '/moshion/textures/', textures: {} };";

/** The moshion repo's built docs file, as a TypeScript module shCode imports. */
function docsModule(js, commit) {
  const data = JSON.parse(js.trim().replace(/^window\.MOSHION_DOCS\s*=\s*/, '').replace(/;\s*$/, ''));
  return `// GENERATED by scripts/sync-moshion.mjs from the moshion repo's docs/data/moshion-docs.js
// (commit ${commit}). Do not edit: change docs/content/ in the moshion repo, then sync.
// shCode's own pages are lib/moshion-docs-shcode.ts; lib/moshion-docs.ts joins the two.
import type { DocSection } from './docs-core';

export const SHARED_DOCS_COMMIT = '${commit}';

export const sharedSections: DocSection[] = ${JSON.stringify(data, null, 1)};
`;
}

const FILES = [
  { from: 'moshion.js', to: 'public/moshion/moshion.js', patch: true },
  { from: 'docs/moshion.d.ts', to: 'public/moshion/docs/moshion.d.ts' },
  { from: 'planck.min.js', to: 'public/moshion/planck.min.js' },
  { from: 'docs/data/moshion-docs.js', to: 'lib/moshion-docs-shared.generated.ts', docs: true },
];

function run(cmd, args, opts = {}) {
  return spawnSync(cmd, args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, ...opts });
}
const git = (...a) => run('git', ['-C', upstream, ...a]);

// --check (the deploy gate) fails CLOSED: a drift it could not check is not
// "in sync". MOSHION_ALLOW_BEHIND=1 is the one way past it (offline, or an
// urgent shCode-only fix), and it is said out loud.
function skip(msg) {
  console.log(`[sync-moshion] ${msg}`);
  if (checkOnly && process.env.MOSHION_ALLOW_BEHIND !== '1') {
    console.log('[sync-moshion] cannot confirm the vendored engine matches upstream, so the deploy stops. MOSHION_ALLOW_BEHIND=1 goes ahead anyway.');
    process.exit(1);
  }
  process.exit(checkOnly ? 0 : 1);
}

if (!existsSync(join(upstream, '.git'))) skip(`no moshion checkout at ${upstream}; set MOSHION_DIR to check drift`);
if (REF.startsWith('origin/')) {
  const f = git('fetch', '-q', 'origin');
  if (f.status !== 0) {
    if (checkOnly) skip('could not reach origin (offline?); drift not checked.');
    console.error('git fetch failed:\n' + (f.stderr || ''));
    process.exit(1);
  }
}
const head = git('rev-parse', '--short', REF).stdout.trim();
if (!head) skip(`no ${REF} in ${upstream}`);

function upstreamText(file) {
  const r = git('show', `${REF}:${file.from}`);
  if (r.status !== 0) throw new Error(`${REF} has no ${file.from}`);
  let t = r.stdout;
  if (file.patch) {
    if (!t.includes(UP_LINE)) throw new Error(`moshion.js no longer contains the textures base line; update UP_LINE in ${fileURLToPath(import.meta.url)}`);
    t = t.replace(UP_LINE, OUR_LINE);
  }
  if (file.docs) t = docsModule(t, head);
  return t;
}

const drifted = [];
for (const file of FILES) {
  const want = upstreamText(file);
  const have = existsSync(join(root, file.to)) ? readFileSync(join(root, file.to), 'utf8') : '';
  // The docs module stamps the commit it came from; compare it without that line.
  const norm = (t) => (file.docs ? t.replace(/commit [0-9a-f]+\)|'[0-9a-f]{7,}';/g, '') : t);
  if (norm(want) !== norm(have)) drifted.push({ ...file, want });
}

const vendoredDoc = join(vendored, 'VENDORED.md');
const doc = readFileSync(vendoredDoc, 'utf8');
const pinned = (doc.match(/\| Commit \| `([0-9a-f]{7,})`/) || [])[1];

if (checkOnly) {
  if (!drifted.length) {
    console.log(`[sync-moshion] in sync with upstream ${REF} (${head}).`);
    process.exit(0);
  }
  const behind = pinned ? git('rev-list', '--count', `${pinned}..${REF}`).stdout.trim() : '?';
  console.log(`[sync-moshion] the vendored engine differs from upstream ${REF} (${head}; pinned ${pinned || 'unknown'}, ${behind} commit(s) ahead).`);
  console.log(`[sync-moshion] differs: ${drifted.map((d) => d.to).join(', ')}. Bring it in with: npm run sync:moshion`);
  console.log('[sync-moshion] (a difference with nothing newer upstream means shCode has a local edit: make it upstream first)');
  if (process.env.MOSHION_ALLOW_BEHIND === '1') { console.log('[sync-moshion] MOSHION_ALLOW_BEHIND=1: going ahead anyway.'); process.exit(0); }
  process.exit(1);
}

if (!drifted.length) {
  console.log(`[sync-moshion] already identical to upstream ${REF} (${head}); nothing to copy.`);
  process.exit(0);
}

const dtsPath = join(vendored, 'docs/moshion.d.ts');
const dtsBefore = existsSync(dtsPath) ? readFileSync(dtsPath, 'utf8') : '';
for (const d of drifted) {
  writeFileSync(join(root, d.to), d.want);
  console.log(`[sync-moshion] updated ${d.to}`);
}

// Stamp the pin so the next --check measures from here.
const date = git('log', '-1', '--format=%cs', REF).stdout.trim();
const stamped = doc.replace(/\| Commit \| `[0-9a-f]{7,}`/, `| Commit | \`${head}\``).replace(/\| Commit date \| [0-9-]+ \|/, `| Commit date | ${date} |`);
if (stamped === doc && pinned !== head) console.log('[sync-moshion] could not find the Commit row in VENDORED.md; update it by hand.');
writeFileSync(vendoredDoc, stamped);

const steps = [
  'generate-moshion-completions.mjs',
  'check-moshion-textures.mjs',
  'test-moshion-docs.mjs',
  'test-moshion.mjs',
  'test-moshion-extras.mjs',
  'test-editor-completions.mjs',
  'check-docs-prose.mjs',
  'check-moshion-docs-coverage.mjs',
];
let failed = false;
for (const s of steps) {
  const r = run(process.execPath, [...NODE, join('scripts', s)], { cwd: root });
  const ok = r.status === 0;
  console.log(`[sync-moshion] ${ok ? 'ok  ' : 'FAIL'} ${s}`);
  if (!ok) { failed = true; console.log(((r.stdout || '') + (r.stderr || '')).split('\n').slice(-12).join('\n')); }
}

const dtsAfter = readFileSync(dtsPath, 'utf8');
if (dtsAfter !== dtsBefore) {
  console.log('\n[sync-moshion] the API typings changed. Its docs come with it from the moshion repo; check shCode\'s own pages (lib/moshion-docs-shcode.ts) still say the right thing:');
  console.log('  git diff public/moshion/docs/moshion.d.ts');
}
console.log(failed
  ? '\n[sync-moshion] a gate FAILED. Do not deploy; fix, or revert with: git checkout public/moshion lib'
  : `\n[sync-moshion] synced to upstream ${head}. Review, commit, then deploy.`);
process.exit(failed ? 1 : 0);
