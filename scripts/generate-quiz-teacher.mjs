// Bakes every multiple-choice quiz's questions, options and answer index into
// functions/_shared/quiz-teacher.generated.ts, for the TEACHER's review views (ux2 T3b).
//
// WHY THIS EXISTS: a teacher reading a quiz hand-in saw "Choice A, Wrong" -- the
// stored hand-in keeps only the option INDEX the student picked, and the option
// text lives in lessons/*/lesson.json, which a Pages Function cannot read at
// runtime. The teacher needs "Picked: <text>. Answer: <text>" to explain a mistake.
//
// It is a bundled worker module, NOT a public/ file, for the same reason as
// generate-quiz-keys.mjs: anything in public/ can be fetched by anyone, and this
// holds every quiz's key, summative tests included. It is read only by the
// teacher/admin-gated GET /api/classes/[id]/submission-queue
// (functions/_shared/quizTeacher.ts). Do not import it from app/ or components/.
//
// Rerun by prebuild. After editing a quiz locally:
//   node scripts/generate-quiz-teacher.mjs

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const lessonsDir = path.join(root, 'lessons');
const outFile = path.join(root, 'functions', '_shared', 'quiz-teacher.generated.ts');

const out = {};
for (const id of readdirSync(lessonsDir).sort()) {
  const file = path.join(lessonsDir, id, 'lesson.json');
  if (!existsSync(file)) continue;
  let lesson;
  try {
    lesson = JSON.parse(readFileSync(file, 'utf8'));
  } catch {
    continue; // generate-lessons-manifest.mjs reports a broken lesson.json; this only skips it
  }
  const questions = lesson?.quiz?.questions;
  if (!Array.isArray(questions) || questions.length === 0) continue;
  const rows = [];
  for (const q of questions) {
    if (!q || typeof q.id !== 'string' || !Array.isArray(q.options)) continue;
    const options = q.options.filter((o) => typeof o === 'string');
    if (options.length !== q.options.length) continue;
    rows.push({
      id: q.id,
      question: typeof q.question === 'string' ? q.question : typeof q.prompt === 'string' ? q.prompt : '',
      options,
      answer: Number.isInteger(q.answer) && q.answer >= 0 && q.answer < options.length ? q.answer : null,
    });
  }
  if (rows.length > 0) out[lesson.id ?? id] = { questions: rows };
}

const body = JSON.stringify(out, null, 2);
writeFileSync(
  outFile,
  `// GENERATED by scripts/generate-quiz-teacher.mjs from lessons/*/lesson.json -- do not edit.
//
// Every multiple-choice quiz's questions, options and answer index, for the TEACHER's
// review views only (functions/_shared/quizTeacher.ts, read by the teacher/admin-gated
// GET /api/classes/[id]/submission-queue). Bundled into the Pages Function worker;
// NEVER a static asset, and never imported from app/ or components/: it holds every
// quiz's answer key. Regenerated by prebuild.

import type { TeacherQuiz } from '../../lib/teacher-drawer';

export const QUIZ_TEACHER: Record<string, TeacherQuiz> = ${body};
`,
);

const n = Object.values(out).reduce((k, v) => k + v.questions.length, 0);
console.log(`generate-quiz-teacher: ${Object.keys(out).length} quizzes, ${n} questions -> functions/_shared/quiz-teacher.generated.ts`);
