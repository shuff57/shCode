// Bakes every summative quiz's answer key into functions/_shared/quiz-keys.generated.ts.
//
// WHY THIS EXISTS: /api/quiz-reveal must read the key SERVER-side, and a Pages
// Function cannot read lessons/ at runtime. A public/ JSON file (the pattern
// generate-ai-graders.mjs uses for rubrics) would not do here: anything in
// public/ is fetchable by anyone, and a URL that hands over every form's key in
// one request is exactly the leak lib/quiz-redact.ts and
// scripts/check-quiz-key-leak.mjs exist to prevent. So the key is written as a
// TypeScript module that is bundled into the Function worker at deploy and is
// never a static asset.
//
// Only quiz.summative lessons are emitted. A lesson missing from the map makes
// /api/quiz-reveal refuse (fail closed), which is also what keeps a
// non-summative quiz's key from ever having a reveal path.
//
// Rerun by prebuild. If you edit a summative lesson locally, rerun:
//   node scripts/generate-quiz-keys.mjs

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const lessonsDir = path.join(root, 'lessons');
const outFile = path.join(root, 'functions', '_shared', 'quiz-keys.generated.ts');

const out = {};
const errors = [];

for (const id of readdirSync(lessonsDir)) {
  const file = path.join(lessonsDir, id, 'lesson.json');
  if (!existsSync(file)) continue;

  let lesson;
  try {
    lesson = JSON.parse(readFileSync(file, 'utf8'));
  } catch (e) {
    errors.push(`${id}: lesson.json does not parse -- ${e.message}`);
    continue;
  }

  const quiz = lesson.quiz;
  // Opt-in, not "every summative quiz". `summative` is set on five quizzes in
  // the course and two of them (1-3-21, 2-1-39) are MODULE quizzes, where
  // marking and explaining is the whole point and always was. Emitting on
  // `summative` alone would silently switch on "here are the correct answers"
  // for the Chapter 1 and Chapter 3 tests as well -- a policy change nobody
  // decided. So a quiz earns a reveal by asking for one.
  // A capped quiz (maxSubmissions) is also emitted: the server scores each try
  // from this key and holds the answers back until the last try is spent.
  if (!quiz || !quiz.summative || (quiz.revealAfterSubmit !== true && typeof quiz.maxSubmissions !== 'number')) continue;

  const questions = (quiz.questions ?? []).map((q) => {
    if (typeof q.answer !== 'number') {
      errors.push(`${id}: question ${q.id} has no numeric "answer"`);
      return null;
    }
    if (typeof q.explanation !== 'string') {
      errors.push(`${id}: question ${q.id} has no "explanation"`);
      return null;
    }
    const optionText = (q.options ?? [])[q.answer];
    if (typeof optionText !== 'string') {
      errors.push(`${id}: question ${q.id} answer index ${q.answer} has no matching option`);
      return null;
    }
    return {
      id: q.id,
      answer: q.answer,
      optionText,
      explanation: q.explanation,
      ...(q.variant ? { variant: q.variant } : {}),
    };
  });
  if (errors.length) break;

  out[id] = {
    ...(typeof quiz.maxSubmissions === 'number' ? { maxSubmissions: quiz.maxSubmissions } : {}),
    ...(quiz.variants ? { variants: quiz.variants } : {}),
    questions,
  };
}

if (errors.length) {
  console.error('generate-quiz-keys: FAILED');
  for (const e of errors) console.error(' ' + e);
  process.exit(1);
}

const body = JSON.stringify(out, null, 2)
  .replace(/\n/g, '\n  ')
  .slice(0, -2) + '\n}';

writeFileSync(
  outFile,
  `// GENERATED by scripts/generate-quiz-keys.mjs from lessons/*/lesson.json -- do not edit.
//
// The summative quiz answer key, read server-side by functions/api/quiz-reveal.ts.
// Bundled into the Pages Function worker at deploy; NEVER served as a static
// asset (a public/ file is fetchable by anyone, which is the exact leak
// lib/quiz-redact.ts prevents). Do not import this from anything under app/
// or components/ -- the browser must never receive this module.
// Regenerated by prebuild; rerun manually after editing a summative lesson.

export interface QuizKeyQuestion {
  id: string;
  /** Index into the question's authored options array, never the drawn order. */
  answer: number;
  optionText: string;
  explanation: string;
  variant?: string;
}

export interface QuizKey {
  /** Set on a capped quiz: answers are held back until this many tries are spent. */
  maxSubmissions?: number;
  variants?: string[];
  questions: QuizKeyQuestion[];
}

export const QUIZ_KEYS: Record<string, QuizKey> = ${body}
`,
);

const n = Object.values(out).reduce((k, v) => k + v.questions.length, 0);
console.log(
  `generate-quiz-keys: ${Object.keys(out).length} summative quiz(zes), ${n} questions -> functions/_shared/quiz-keys.generated.ts`,
);
