// Bakes two server-only tables into functions/_shared/pa-pseudocode.generated.ts:
//
//   ATTEMPT_CAPS   lessonId -> maxSubmissions, for every lesson that sets one
//   PA_PSEUDOCODE  lessonId -> the solution as plain-language pseudocode
//
// WHY A GENERATED SERVER MODULE. The pseudocode is the answer to a graded part
// and is shown only after the student has spent every try
// (functions/api/attempt-reveal.ts). A Pages Function cannot read the repo at
// runtime and anything under public/ is fetchable by anyone, so the text is
// compiled into the worker like quiz-keys.generated.ts and ai-graders.generated.ts.
// The caps come from the same place for the same reason: the server decides
// whether a student has used their tries, and it must not take that number from
// the browser.
//
// Source of the text: pa-pseudocode/<lessonId>.md, a top-level folder. Not
// lessons/<id>/solution/: that collides with solution.js (a lesson with both
// fails the build) and lib/lessons.ts ships whatever it finds under lessons/.
// With no pseudocode files the store is simply empty, and the reveal route
// answers 404 for every lesson (fails closed).
//
//   node scripts/generate-pa-pseudocode.mjs

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lessonsDir = path.join(root, 'lessons');
const pseudoDir = path.join(root, 'pa-pseudocode');
const outFile = path.join(root, 'functions', '_shared', 'pa-pseudocode.generated.ts');

const errors = [];
const caps = {};
const known = new Set();

for (const id of readdirSync(lessonsDir).sort()) {
  const file = path.join(lessonsDir, id, 'lesson.json');
  if (!existsSync(file)) continue;
  known.add(id);
  let lesson;
  try {
    lesson = JSON.parse(readFileSync(file, 'utf8'));
  } catch (e) {
    errors.push(`${id}: lesson.json does not parse -- ${e.message}`);
    continue;
  }
  // The block the part's renderer reads. A chart's AI block sits under diagram.
  const blocks = [lesson.quiz, lesson.aiGrader, lesson.diagram, lesson.diagram && lesson.diagram.aiGrader, lesson.grading];
  const values = blocks
    .filter((b) => b && typeof b === 'object' && 'maxSubmissions' in b)
    .map((b) => b.maxSubmissions);
  if (values.length === 0) continue;
  if (new Set(values).size > 1) {
    errors.push(`${id}: maxSubmissions disagrees between blocks (${values.join(', ')})`);
    continue;
  }
  const n = values[0];
  if (!Number.isInteger(n) || n < 1) {
    errors.push(`${id}: maxSubmissions must be a whole number >= 1, got ${JSON.stringify(n)}`);
    continue;
  }
  caps[id] = n;
}

const pseudocode = {};
if (existsSync(pseudoDir)) {
  for (const f of readdirSync(pseudoDir).sort()) {
    if (!f.endsWith('.md')) continue;
    const id = f.slice(0, -3);
    if (!known.has(id)) {
      errors.push(`pa-pseudocode/${f}: no lesson called ${id}`);
      continue;
    }
    if (!(id in caps)) {
      errors.push(`pa-pseudocode/${f}: ${id} sets no maxSubmissions, so the text could never be shown`);
      continue;
    }
    const text = readFileSync(path.join(pseudoDir, f), 'utf8').trim();
    if (text.length < 40) {
      errors.push(`pa-pseudocode/${f}: too short to be a solution (${text.length} chars)`);
      continue;
    }
    pseudocode[id] = text;
  }
}

if (errors.length) {
  console.error('generate-pa-pseudocode: FAILED');
  for (const e of errors) console.error('  ' + e);
  process.exit(1);
}

writeFileSync(
  outFile,
  `// GENERATED by scripts/generate-pa-pseudocode.mjs -- do not edit.
//
// Server-only. ATTEMPT_CAPS is read by functions/api/attempt-reveal.ts,
// quiz-reveal.ts, lesson-state and lesson-submissions; PA_PSEUDOCODE is the
// answer text and is handed out only by attempt-reveal, only to a student with
// every try spent. Bundled into the Pages Function worker at deploy and NEVER a
// static asset. Do not import this from app/ or components/: the browser must
// never receive it (scripts/check-ai-grader-leak.mjs probes public/ and out/).

export const ATTEMPT_CAPS: Record<string, number> = ${JSON.stringify(caps, null, 2)};

export const PA_PSEUDOCODE: Record<string, string> = ${JSON.stringify(pseudocode, null, 2)};
`,
);
console.log(
  `generate-pa-pseudocode: ${Object.keys(caps).length} capped lesson(s), ${Object.keys(pseudocode).length} pseudocode file(s) -> functions/_shared/pa-pseudocode.generated.ts`,
);
