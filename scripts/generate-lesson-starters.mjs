// Generates functions/_shared/lesson-starters.generated.ts — a server-only map of
// lessonId → { filename: content } so the teacher-edit page can diff student work
// against the original starter files.
//
// Mirrors the pattern of scripts/generate-solutions.mjs.

import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const lessonsDir = path.join(root, 'lessons');
const outPath = path.join(root, 'functions', '_shared', 'lesson-starters.generated.ts');

async function readFiles(dir, rel = '') {
  /** @type {Record<string, string>} */
  const files = {};
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    // Skip metadata and the reference answer. solution/ is the multi-file form
    // of solution.js; this loop recurses, so it must be skipped by name or the
    // answer key lands in the starter bundle every student downloads.
    if (entry.name === 'lesson.json' || entry.name === 'solution.js') continue;
    if (entry.isDirectory() && entry.name === 'solution') continue;
    const full = path.join(dir, entry.name);
    const relative = path.join(rel, entry.name).replace(/\\/g, '/');
    if (entry.isDirectory()) {
      Object.assign(files, await readFiles(full, relative));
    } else {
      files[relative] = await fs.readFile(full, 'utf8');
    }
  }
  return files;
}

const entries = await fs.readdir(lessonsDir, { withFileTypes: true });
// A folder starting with _ (lessons/_retired/) is not a lesson and must not
// reach the worker bundle -- it once carried the retired JSCAD starters to prod.
const dirs = entries.filter((e) => e.isDirectory() && !e.name.startsWith('_')).map((e) => e.name);

/** @type {Record<string, Record<string, string>>} */
const map = {};
for (const id of dirs) {
  const files = await readFiles(path.join(lessonsDir, id));
  if (Object.keys(files).length > 0) {
    map[id] = files;
  }
}

const sortedIds = Object.keys(map).sort();
const lines = sortedIds.map((id) => {
  const filesJson = JSON.stringify(map[id]);
  return `  ${JSON.stringify(id)}: ${filesJson},`;
});

const body =
  '// AUTO-GENERATED by scripts/generate-lesson-starters.mjs — do not edit.\n' +
  '// Source: lessons/<id>/* (excluding lesson.json and solution.js).\n\n' +
  'export const STARTERS: Record<string, Record<string, string>> = {\n' +
  lines.join('\n') +
  '\n};\n';

await fs.mkdir(path.dirname(outPath), { recursive: true });
await fs.writeFile(outPath, body);
console.log(
  `[generate-lesson-starters] wrote ${sortedIds.length} lesson starter(s) → functions/_shared/lesson-starters.generated.ts`,
);
