// Bakes every curriculum module's rendered markdown into
// functions/_shared/module-docs.generated.ts so a role-gated API can serve it.
//
// WHY THIS EXISTS. app/module/[moduleId]/page.tsx rendered the module markdown
// (the teacher reference) inside <TeacherOnly>, a client component. On a
// statically exported site the HTML is serialised into the RSC payload before
// any client gate runs — measured 2026-09-18 on /module/2.7: the full teacher
// doc, including 2.7.3's answer-key table (beforTax, let shipping = 5;) and
// the 2.7.1 trace topics, shipped to every signed-out visitor. TeacherOnly
// governs what is DRAWN; nothing governed what is SHIPPED. This is the exact
// class of leak lib/quiz-redact.ts fixed for lessons; module pages were never
// covered. The static page now ships only summary + lessons; the teacher
// reference travels through GET /api/module-doc/[id], which enforces the role
// server-side, and a client panel renders it only after that fetch succeeds.
//
// The generated file is committed? No — like solutions.generated.ts it is
// derived (from curriculum/modules/*.md) and regenerated by prebuild.
//
//   node scripts/generate-module-docs.mjs

import { readFileSync, readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const modulesDir = path.join(root, 'curriculum', 'modules');
const outFile = path.join(root, 'functions', '_shared', 'module-docs.generated.ts');

// Minimal markdown -> HTML. The page renders this for teachers only; it never
// needs the full renderer, but it must not mangle tables or code fences.
function esc(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
function mdToHtml(src) {
  const lines = src.split('\n');
  const out = [];
  let inCode = false;
  let inTable = false;
  for (let raw of lines) {
    let line = raw;
    if (line.trim().startsWith('```')) {
      if (inCode) { out.push('</code></pre>'); inCode = false; }
      else { out.push('<pre><code>'); inCode = true; }
      continue;
    }
    if (inCode) { out.push(esc(line)); continue; }
    if (/^\|/.test(line.trim())) {
      const cells = line.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
      if (/^[\s|:-]+$/.test(line.trim())) continue; // separator row
      if (!inTable) { out.push('<table>'); inTable = true; out.push('<tr>' + cells.map((c) => `<th>${c}</th>`).join('') + '</tr>'); continue; }
      out.push('<tr>' + cells.map((c) => `<td>${c}</td>`).join('') + '</tr>');
      continue;
    }
    if (inTable) { out.push('</table>'); inTable = false; }
    const h = line.match(/^(#{1,4})\s+(.*)$/);
    if (h) { out.push(`<h${h[1].length}>${esc(h[2])}</h${h[1].length}>`); continue; }
    if (line.trim() === '') { out.push(''); continue; }
    if (line.trim() === '---') { out.push('<hr>'); continue; }
    // blockquote
    if (line.trim().startsWith('>')) {
      out.push(`<blockquote>${esc(line.trim().replace(/^>\s?/, ''))}</blockquote>`);
      continue;
    }
    // inline code and bold, then escape
    line = esc(line)
      .replace(/`([^`]+)`/g, '<code>$1</code>')
      .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
      .replace(/\*([^*]+)\*/g, '<em>$1</em>');
    out.push(`<p>${line}</p>`);
  }
  if (inTable) out.push('</table>');
  if (inCode) out.push('</code></pre>');
  return out.join('\n');
}

function parseFrontmatter(src) {
  const m = src.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return { meta: {}, body: src };
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^(\w[\w-]*):\s*(.*)$/);
    if (kv) meta[kv[1]] = kv[2].replace(/^["']|["']$/g, '');
  }
  return { meta, body: src.slice(m[0].length) };
}

const out = {};
const errors = [];
for (const f of readdirSync(modulesDir)) {
  if (!f.endsWith('.md') || f.startsWith('_')) continue; // _build-spec-* has no frontmatter, same skip as the starters walker
  const slug = f.replace(/\.md$/, '');
  const src = readFileSync(path.join(modulesDir, f), 'utf8');
  const { meta, body } = parseFrontmatter(src);
  const id = meta.id;
  if (!id) { errors.push(`${f}: no id in frontmatter`); continue; }
  out[id] = {
    title: meta.title ?? slug,
    html: mdToHtml(body),
  };
}

if (errors.length) {
  console.error('generate-module-docs: FAILED');
  for (const e of errors) console.error('  ' + e);
  process.exit(1);
}

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  '// GENERATED by scripts/generate-module-docs.mjs — do not edit.\n'
  + '// Rendered teacher reference for every curriculum module. Shipped ONLY\n'
  + '// through GET /api/module-doc/[id], which enforces teacher/admin role.\n'
  + '// The static module page must never embed this: TeacherOnly hides display,\n'
  + '// not shipment (measured leak on /module/2.7, 2026-09-18).\n'
  + 'export const MODULE_DOCS: Record<string, { title: string; html: string }> = '
  + JSON.stringify(out)
  + ';\n',
);
const total = Object.values(out).reduce((n, g) => n + g.html.length, 0);
console.log(`generate-module-docs: ${Object.keys(out).length} modules, ${total0(total)} chars -> functions/_shared/module-docs.generated.ts`);
function total0(n) { return n.toLocaleString('en-US'); }