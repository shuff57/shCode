// Generates functions/_shared/solutions.generated.ts — a server-only map of
// lessonId → { filePath: text }. The Pages Function at
// /api/lesson-solution/[id] reads this map and gates it to admin/teacher.
//
// Three authoring forms, in priority order:
//
//   lessons/<id>/solution/      every file in it, keyed by its path relative
//                               to solution/. Use this when the assignment
//                               grades more than script.js.
//   lessons/<id>/solution.js    the single-file form. Recorded as script.js.
//   (neither, but quiz.summative: true)
//                               an answer key is SYNTHESISED from the
//                               lesson's own lesson.json — every question,
//                               every form, the correct option and its
//                               explanation. Not hand-authored, so it cannot
//                               drift from the quiz a student actually sees:
//                               lib/quiz-redact.ts strips this same data out
//                               of the client bundle, this script reads it
//                               from the source lesson.json, which still has
//                               it. See buildQuizAnswerKey below.
//
// A lesson with both solution/ and solution.js is a mistake — the directory
// wins and this script says so loudly, because a stale solution.js sitting
// beside a solution/ is exactly the kind of second copy that drifts.
//
// None of the three reaches the static client bundle: lib/lessons.ts and
// scripts/generate-lesson-starters.mjs both exclude solution/ and
// solution.js, and the synthesised key is never written to disk at all — so
// this generated file is the only path by which a reference answer ever
// leaves the repo.

import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
import { buildQuizAnswerKey } from '../lib/quiz-answer-key.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const lessonsDir = path.join(root, 'lessons');
const outPath = path.join(root, 'functions', '_shared', 'solutions.generated.ts');

async function readDirFiles(dir, rel = '') {
  /** @type {Record<string, string>} */
  const files = {};
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    const relative = path.join(rel, entry.name).replace(/\\/g, '/');
    if (entry.isDirectory()) {
      Object.assign(files, await readDirFiles(full, relative));
    } else {
      files[relative] = await fs.readFile(full, 'utf8');
    }
  }
  return files;
}

const entries = await fs.readdir(lessonsDir, { withFileTypes: true });
const dirs = entries.filter((e) => e.isDirectory()).map((e) => e.name);

/** @type {Record<string, Record<string, string>>} */
const map = {};
let multiFile = 0;

for (const id of dirs) {
  const dirForm = path.join(lessonsDir, id, 'solution');
  const fileForm = path.join(lessonsDir, id, 'solution.js');

  let stat = null;
  try {
    stat = await fs.stat(dirForm);
  } catch {
    /* no solution/ directory */
  }

  if (stat?.isDirectory()) {
    const files = await readDirFiles(dirForm);
    if (Object.keys(files).length === 0) {
      console.error(`[generate-solutions] ${id}: solution/ exists but is empty`);
      process.exit(1);
    }
    map[id] = files;
    if (Object.keys(files).length > 1) multiFile++;
    try {
      await fs.access(fileForm);
      console.error(
        `[generate-solutions] ${id}: has BOTH solution/ and solution.js. ` +
          `Delete solution.js — two copies of a reference answer drift.`,
      );
      process.exit(1);
    } catch {
      /* good — only the directory form */
    }
    continue;
  }

  try {
    map[id] = { 'script.js': await fs.readFile(fileForm, 'utf8') };
    continue;
  } catch {
    /* no solution.js either — fall through to the synthesised quiz key */
  }

  try {
    const lesson = JSON.parse(
      await fs.readFile(path.join(lessonsDir, id, 'lesson.json'), 'utf8'),
    );
    if (lesson.quiz?.summative) {
      map[id] = { 'answer-key.txt': buildQuizAnswerKey(lesson) };
    }
  } catch {
    /* no lesson.json, or it doesn't parse — nothing to synthesise */
  }
}

const sortedIds = Object.keys(map).sort();
const body =
  '// AUTO-GENERATED by scripts/generate-solutions.mjs — do not edit.\n' +
  '// Source: lessons/<id>/solution/ (multi-file) or lessons/<id>/solution.js\n' +
  '// (single-file, recorded as script.js). Regenerated on every build.\n\n' +
  'export const SOLUTIONS: Record<string, Record<string, string>> = {\n' +
  sortedIds
    .map((id) => {
      const files = map[id];
      const inner = Object.keys(files)
        .sort()
        .map((f) => `    ${JSON.stringify(f)}: ${JSON.stringify(files[f])},`)
        .join('\n');
      return `  ${JSON.stringify(id)}: {\n${inner}\n  },`;
    })
    .join('\n') +
  '\n};\n';

await fs.mkdir(path.dirname(outPath), { recursive: true });
await fs.writeFile(outPath, body);
console.log(
  `[generate-solutions] wrote ${sortedIds.length} solution(s), ` +
    `${multiFile} multi-file → functions/_shared/solutions.generated.ts`,
);
