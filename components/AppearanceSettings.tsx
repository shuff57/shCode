'use client';

// The Appearance card on /account (#73, #77): theme, accent colour, body font
// and the home page's background. A choice applies at once (lib/prefs.ts) and
// is saved to the account a moment later, so it follows the student to another
// computer. Every option is a native radio, so arrow keys move within a group
// and the screen reader reads "Theme, Light, 2 of 5".

import { useEffect, useRef, useState } from 'react';
import {
  ACCENTS, ACCENT_LABELS, FONTS, FONT_LABELS, HOME_PRESETS, HOME_PRESET_LABELS, THEMES, THEME_LABELS,
  type HomeBg, type Prefs, type ThemeId,
} from '../lib/prefs-core';
import { pushPrefs, readLocalPrefs, setLocalPrefs } from '../lib/prefs';
import { listUploads, uploadImage, type UploadItem } from '../lib/uploads';
import { backdropStyle } from './HomeBackdrop';

// Preview colours for the theme cards only (the real values are app/themes.css,
// generated by scripts/generate-theme-css.mjs; dark is :root in globals.css).
const SWATCH: Record<ThemeId, { bg: string; fg: string; a: string; b: string }> = {
  dark: { bg: '#282a36', fg: '#f8f8f2', a: '#bd93f9', b: '#50fa7b' },
  light: { bg: '#fbfbf8', fg: '#1d1f2b', a: '#1d5fbf', b: '#1b6e33' },
  candy: { bg: '#fffafc', fg: '#3a1f45', a: '#b4246f', b: '#7b3fc4' },
  retro: { bg: '#0c0c18', fg: '#eef2ff', a: '#22d3ee', b: '#ff6ec7' },
  forest: { bg: '#18271f', fg: '#f2ecd9', a: '#9fd99a', b: '#ebb26b' },
};

const FONT_STACK: Record<(typeof FONTS)[number], string> = {
  classic: "'Courier', monospace",
  modern: "ui-monospace, 'Cascadia Code', 'Fira Code', Menlo, Consolas, monospace",
  sans: "system-ui, -apple-system, 'Segoe UI', Roboto, Arial, sans-serif",
};

const S = {
  card: {
    maxWidth: 560,
    margin: '24px auto 0',
    background: 'var(--c-deep)',
    border: '1px solid var(--c-line)',
    borderRadius: 8,
    padding: 24,
  } as React.CSSProperties,
  h2: { fontSize: 20, fontWeight: 700, margin: '0 0 4px', color: 'var(--c-fg)' } as React.CSSProperties,
  intro: { fontFamily: 'var(--font-prose)', fontSize: 14, lineHeight: 1.5, maxWidth: '70ch', color: 'var(--c-meta)', margin: '0 0 16px' } as React.CSSProperties,
  fieldset: { border: 'none', padding: 0, margin: '0 0 20px', minWidth: 0 } as React.CSSProperties,
  legend: { fontSize: 14, fontWeight: 700, marginBottom: 8, color: 'var(--c-fg)', padding: 0 } as React.CSSProperties,
  grid: (min: number): React.CSSProperties => ({
    display: 'grid',
    gridTemplateColumns: `repeat(auto-fill, minmax(${min}px, 1fr))`,
    gap: 8,
  }),
  // The whole tile is the label, so the hit target is the tile; the radio sits
  // inside it, visually hidden, and the tile shows its focus and checked state.
  tile: (checked: boolean): React.CSSProperties => ({
    position: 'relative',
    display: 'flex',
    flexDirection: 'column',
    gap: 6,
    padding: 8,
    borderRadius: 6,
    cursor: 'pointer',
    border: `2px solid ${checked ? 'var(--brand)' : 'var(--c-line)'}`,
    background: 'var(--c-bg)',
    color: 'var(--c-fg)',
    fontSize: 13,
    minWidth: 0,
  }),
  srOnly: {
    position: 'absolute', width: 1, height: 1, padding: 0, margin: -1, overflow: 'hidden',
    clip: 'rect(0,0,0,0)', whiteSpace: 'nowrap', border: 0,
  } as React.CSSProperties,
  status: { fontSize: 13, minHeight: 20, color: 'var(--c-dim)' } as React.CSSProperties,
};

/** A tile label wrapping a visually hidden radio. */
function Tile(props: {
  name: string; value: string; checked: boolean; onChange: () => void; children: React.ReactNode; title?: string;
}) {
  return (
    <label style={S.tile(props.checked)} className="appearance-tile" title={props.title}>
      <input type="radio" name={props.name} value={props.value} checked={props.checked} onChange={props.onChange} style={S.srOnly} />
      {props.children}
      {props.checked && (
        <span aria-hidden="true" style={{ position: 'absolute', bottom: 6, right: 8, color: 'var(--brand)', fontWeight: 700 }}>✓</span>
      )}
    </label>
  );
}

export default function AppearanceSettings() {
  const [prefs, setPrefs] = useState<Prefs>(() => readLocalPrefs());
  const [status, setStatus] = useState<{ kind: 'ok' | 'error' | 'busy'; text: string } | null>(null);
  const [uploads, setUploads] = useState<UploadItem[] | null>(null);
  const [uploading, setUploading] = useState(false);
  const saveTimer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const pending = useRef<Prefs | null>(null);
  const fileRef = useRef<HTMLInputElement>(null);

  useEffect(() => {
    setPrefs(readLocalPrefs());
    listUploads()
      .then((r) => setUploads(r.uploads.filter((u) => u.content_type.startsWith('image/'))))
      .catch(() => setUploads([]));
    // Leaving within the half-second wait must not lose the choice: send it now.
    const flush = () => {
      if (!saveTimer.current || !pending.current) return;
      clearTimeout(saveTimer.current);
      saveTimer.current = null;
      void pushPrefs(pending.current).catch(() => {});
      pending.current = null;
    };
    window.addEventListener('pagehide', flush);
    return () => { window.removeEventListener('pagehide', flush); flush(); };
  }, []);

  function change(patch: Partial<Prefs>) {
    const next = { ...prefs, ...patch };
    setPrefs(next);
    setLocalPrefs(next);
    setStatus({ kind: 'busy', text: 'Saving…' });
    if (saveTimer.current) clearTimeout(saveTimer.current);
    pending.current = next;
    saveTimer.current = setTimeout(() => {
      saveTimer.current = null;
      pending.current = null;
      pushPrefs(next)
        .then(() => setStatus({ kind: 'ok', text: 'Saved to your account.' }))
        .catch((e: unknown) => setStatus({ kind: 'error', text: `${e instanceof Error ? e.message : String(e)} It still applies on this computer.` }));
    }, 500);
  }

  async function onUpload(file: File | undefined) {
    if (!file) return;
    setUploading(true);
    try {
      const item = await uploadImage(file);
      setUploads((u) => [item, ...(u ?? [])]);
      const ext = item.url.split('.').pop() as 'png';
      change({ homeBg: { kind: 'upload', id: item.id, ext } });
    } catch (e) {
      setStatus({ kind: 'error', text: e instanceof Error ? e.message : String(e) });
    } finally {
      setUploading(false);
      if (fileRef.current) fileRef.current.value = '';
    }
  }

  const bgIs = (bg: HomeBg | null) => JSON.stringify(prefs.homeBg) === JSON.stringify(bg);

  return (
    <section aria-labelledby="appearance-h" style={S.card}>
      <h2 id="appearance-h" style={S.h2}>Appearance</h2>
      <p style={S.intro}>Changes show straight away and follow you to any computer you sign in on.</p>

      <fieldset style={S.fieldset}>
        <legend style={S.legend}>Theme</legend>
        <div style={S.grid(104)}>
          {THEMES.map((t) => {
            const sw = SWATCH[t];
            return (
              <Tile key={t} name="theme" value={t} checked={prefs.theme === t} onChange={() => change({ theme: t })}>
                <span aria-hidden="true" style={{ display: 'block', height: 44, borderRadius: 4, background: sw.bg, border: '1px solid var(--c-line)', padding: 6, boxSizing: 'border-box' }}>
                  <span style={{ display: 'block', height: 5, width: '70%', background: sw.fg, borderRadius: 2, opacity: 0.85 }} />
                  <span style={{ display: 'flex', gap: 4, marginTop: 8 }}>
                    <span style={{ width: 14, height: 10, borderRadius: 2, background: sw.a }} />
                    <span style={{ width: 14, height: 10, borderRadius: 2, background: sw.b }} />
                  </span>
                </span>
                <span>{THEME_LABELS[t]}</span>
              </Tile>
            );
          })}
        </div>
      </fieldset>

      <fieldset style={S.fieldset}>
        <legend style={S.legend}>Accent colour</legend>
        <p style={{ ...S.intro, margin: '-4px 0 8px' }}>Buttons, links and highlights.</p>
        <div style={S.grid(92)}>
          <Tile name="accent" value="" checked={prefs.accent === null} onChange={() => change({ accent: null })}>
            <span aria-hidden="true" style={{ display: 'block', height: 18, borderRadius: 4, background: 'linear-gradient(90deg, var(--c-cyan), var(--c-purple), var(--c-pink))', opacity: 0.6 }} />
            <span>Theme's own</span>
          </Tile>
          {ACCENTS.map((a) => (
            <Tile key={a} name="accent" value={a} checked={prefs.accent === a} onChange={() => change({ accent: a })}>
              <span aria-hidden="true" style={{ display: 'block', height: 18, borderRadius: 4, background: `var(--c-${a})` }} />
              <span>{ACCENT_LABELS[a]}</span>
            </Tile>
          ))}
        </div>
      </fieldset>

      <fieldset style={S.fieldset}>
        <legend style={S.legend}>Font</legend>
        <div style={S.grid(170)}>
          {FONTS.map((f) => (
            <Tile key={f} name="font" value={f} checked={prefs.font === f} onChange={() => change({ font: f })}>
              <span aria-hidden="true" style={{ fontFamily: FONT_STACK[f], fontSize: 15 }}>Aa Bb 123</span>
              <span>{FONT_LABELS[f]}</span>
            </Tile>
          ))}
        </div>
        <p style={{ ...S.intro, margin: '8px 0 0' }}>Code editors always keep their own code font.</p>
      </fieldset>

      <fieldset style={S.fieldset}>
        <legend style={S.legend}>Home page background</legend>
        <div style={S.grid(104)}>
          <Tile name="homeBg" value="none" checked={prefs.homeBg === null} onChange={() => change({ homeBg: null })}>
            <span aria-hidden="true" style={{ display: 'block', height: 44, borderRadius: 4, background: 'var(--bg)', border: '1px solid var(--c-line)' }} />
            <span>Plain</span>
          </Tile>
          {HOME_PRESETS.map((id) => {
            const bg: HomeBg = { kind: 'preset', id };
            return (
              <Tile key={id} name="homeBg" value={id} checked={bgIs(bg)} onChange={() => change({ homeBg: bg })}>
                <span aria-hidden="true" style={{ display: 'block', height: 44, borderRadius: 4, border: '1px solid var(--c-line)', ...backdropStyle(bg) }} />
                <span>{HOME_PRESET_LABELS[id]}</span>
              </Tile>
            );
          })}
          {(uploads ?? []).map((u) => {
            const ext = u.url.split('.').pop() as 'png';
            const bg: HomeBg = { kind: 'upload', id: u.id, ext };
            return (
              <Tile key={u.id} name="homeBg" value={u.id} checked={bgIs(bg)} onChange={() => change({ homeBg: bg })} title={u.filename}>
                {/* eslint-disable-next-line @next/next/no-img-element */}
                <img src={u.url} alt="" width={88} height={44} loading="lazy" style={{ display: 'block', width: '100%', height: 44, objectFit: 'cover', borderRadius: 4 }} />
                <span style={{ overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap' }}>{u.filename}</span>
              </Tile>
            );
          })}
        </div>
        <div style={{ marginTop: 10, display: 'flex', alignItems: 'center', gap: 10, flexWrap: 'wrap' }}>
          <input
            ref={fileRef}
            id="appearance-upload"
            type="file"
            accept="image/png,image/jpeg,image/gif,image/webp"
            onChange={(e) => onUpload(e.target.files?.[0])}
            style={S.srOnly}
            tabIndex={-1}
            aria-hidden="true"
          />
          <button type="button" className="btn-secondary" disabled={uploading} onClick={() => fileRef.current?.click()}>
            {uploading ? 'Uploading…' : 'Use my own image…'}
          </button>
          <span style={{ fontSize: 12, color: 'var(--c-dim)' }}>
            PNG, JPEG, GIF or WebP up to 2&nbsp;MB. It is saved with your uploaded images, and anyone with its link can see it, so keep it school-friendly.
          </span>
        </div>
      </fieldset>

      <div role="status" aria-live="polite" style={{ ...S.status, color: status?.kind === 'error' ? 'var(--c-red)' : 'var(--c-dim)' }}>
        {status?.text ?? ''}
      </div>
    </section>
  );
}
